"""Fixed escalation copy.

These are the highest-liability sentences in the product. They are here, as literal
strings, rather than generated by the model, because a red flag is exactly the moment
when a plausible-sounding paraphrase is most dangerous: when a rule fires, the drafted
LLM reply is thrown away and one of these is sent instead. The exact text shown is
persisted on the escalation row, so what the patient was told is recoverable years
later.

**Every entry is marked `sme_reviewed=False`.** The specification is explicit that
this copy must be written by a clinician, not by a developer and not by a model. What
follows is scaffolding that keeps the pipeline honest and testable — it says the
right kind of thing, in the right register, without diagnosing or prescribing — and
it is not signed off. `sme_reviewed` exists so that "not yet reviewed" is a visible
property of the data rather than an assumption, and so that a release gate can check
it. See docs/roadmap.md, SME question 3.

The copy obeys the conversational constraints in docs/safety-rules.md: it never
diagnoses, never names a probable cause, never estimates risk, never starts or
changes a medication, and never reassures once a rule has fired.
"""

from __future__ import annotations

from dataclasses import dataclass

from app.domain.enums import Route
from app.domain.schemas import Finding


@dataclass(frozen=True)
class EscalationTemplate:
    """One fixed patient-facing message, keyed by rule or by route."""

    key: str
    text: str
    routes: tuple[Route, ...]
    sme_reviewed: bool = False


def _template(key: str, routes: tuple[Route, ...], text: str) -> EscalationTemplate:
    return EscalationTemplate(key=key, text=" ".join(text.split()), routes=routes)


