def escalation_copy(finding: Finding) -> EscalationTemplate:
    """The exact text to send for `finding`.

    Falls back to route-level copy rather than raising, because a rule with a missing
    template must still produce a message — silence is the one unacceptable outcome
    when a red flag has fired. `tests/test_safety.py` asserts every RED rule resolves
    a template of its own, so the fallback is a safety net, not a routine path.
    """
    if finding.escalation_template_key:
        template = TEMPLATES.get(finding.escalation_template_key)
        if template is not None:
            return template
    return ROUTE_FALLBACKS[finding.routes[0]]


def unreviewed_template_keys() -> list[str]:
    """Templates no clinician has signed off. A release gate reads this."""
    return sorted(key for key, template in TEMPLATES.items() if not template.sme_reviewed)
